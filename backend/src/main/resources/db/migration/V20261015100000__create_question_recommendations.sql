CREATE TABLE question_recommendation_jobs
(
    feed_id        BIGINT PRIMARY KEY REFERENCES feeds (id) ON DELETE CASCADE,
    generation     INTEGER                  NOT NULL CHECK (generation > 0),
    status         VARCHAR(20)              NOT NULL CHECK (status IN ('PENDING', 'PROCESSING', 'READY', 'FAILED')),
    source_title   VARCHAR(100)             NOT NULL,
    source_content VARCHAR(5000)            NOT NULL,
    attempt_count  INTEGER                  NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    lease_until    TIMESTAMP WITH TIME ZONE,
    last_error     VARCHAR(100),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_question_recommendation_jobs_status_updated
    ON question_recommendation_jobs (status, updated_at);

CREATE TABLE question_recommendation_items
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feed_id      BIGINT                  NOT NULL REFERENCES question_recommendation_jobs (feed_id) ON DELETE CASCADE,
    generation   INTEGER                 NOT NULL CHECK (generation > 0),
    display_order SMALLINT               NOT NULL CHECK (display_order > 0),
    title        VARCHAR(100)             NOT NULL,
    content      VARCHAR(5000)            NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_question_recommendation_items_generation_order
        UNIQUE (feed_id, generation, display_order)
);

CREATE INDEX idx_question_recommendation_items_generation
    ON question_recommendation_items (feed_id, generation);

CREATE TABLE question_recommendation_outbox
(
    id               UUID PRIMARY KEY,
    feed_id          BIGINT                  NOT NULL REFERENCES question_recommendation_jobs (feed_id) ON DELETE CASCADE,
    generation       INTEGER                 NOT NULL CHECK (generation > 0),
    status           VARCHAR(20)              NOT NULL CHECK (status IN ('PENDING', 'PROCESSING', 'SENT', 'FAILED')),
    attempt_count    INTEGER                  NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    next_attempt_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    lease_until      TIMESTAMP WITH TIME ZONE,
    last_error       VARCHAR(100),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at          TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_question_recommendation_outbox_generation UNIQUE (feed_id, generation)
);

CREATE INDEX idx_question_recommendation_outbox_due
    ON question_recommendation_outbox (status, next_attempt_at, created_at);
