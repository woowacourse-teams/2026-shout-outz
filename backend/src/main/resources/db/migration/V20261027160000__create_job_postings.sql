-- 운영자가 등록한 채용공고와 공고에서 뽑은 역량 항목.
-- 공고 원문은 저작권 위험 때문에 저장하지 않고, 같은 공고인지 판별할 해시만 남긴다.
CREATE TABLE job_postings
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_url         VARCHAR(1024)            NOT NULL,
    content_hash       CHAR(64)                 NOT NULL,
    company_name       VARCHAR(100)             NOT NULL,
    job_role           VARCHAR(20)              NOT NULL CHECK (job_role IN ('BACKEND', 'FRONTEND', 'ANDROID', 'IOS', 'DEVOPS', 'DATA', 'AI', 'ETC')),
    career_requirement VARCHAR(50),
    title              VARCHAR(200)             NOT NULL,
    employment_type    VARCHAR(30),
    deadline           DATE,
    status             VARCHAR(20)              NOT NULL CHECK (status IN ('PENDING', 'PROCESSING', 'READY', 'FAILED')),
    hidden_at          TIMESTAMP WITH TIME ZONE,
    registered_by      BIGINT                   NOT NULL REFERENCES users (id),
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_job_postings_source_url UNIQUE (source_url)
);

-- status, attempt_count, lease_until, last_error는 역량마다 맞는 자료를 찾는 매칭 작업이 쓴다.
-- 등록할 때는 PENDING으로만 저장한다.
CREATE TABLE job_requirements
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_posting_id BIGINT                   NOT NULL REFERENCES job_postings (id) ON DELETE CASCADE,
    display_order  SMALLINT                 NOT NULL CHECK (display_order > 0),
    name           VARCHAR(100)             NOT NULL,
    category       VARCHAR(20)              NOT NULL CHECK (category IN ('REQUIRED', 'PREFERRED', 'DUTY_OR_STACK')),
    summary        VARCHAR(500)             NOT NULL,
    status         VARCHAR(20)              NOT NULL CHECK (status IN ('PENDING', 'PROCESSING', 'READY', 'FAILED')),
    attempt_count  INTEGER                  NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    lease_until    TIMESTAMP WITH TIME ZONE,
    last_error     VARCHAR(100),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_job_requirements_order UNIQUE (job_posting_id, display_order)
);
