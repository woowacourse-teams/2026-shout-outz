-- 실패한 역량을 바로 다시 잡지 않고 이 시각이 지난 뒤에 다시 잡는다.
ALTER TABLE job_requirements
    ADD COLUMN next_attempt_at TIMESTAMP WITH TIME ZONE;

-- 매칭 작업이 10초마다 가져갈 역량을 찾는다. 끝난 역량이 쌓여도 인덱스는 대기, 분석 중인 역량만 담는다.
CREATE INDEX idx_job_requirements_matching_queue
    ON job_requirements (id)
    WHERE status IN ('PENDING', 'PROCESSING');

-- 역량마다 판정한 자료. 자료 테이블의 id는 다시 적재하면 바뀌어서 source + external_key로 가리키고 외래 키는 걸지 않는다.
-- evidence는 판정할 때 LLM에게 보여 준 조각의 복사본이다. 조각은 다시 만들면 id와 내용이 바뀌어 판정 근거를 다시 볼 수 없기 때문이다.
-- reason, description은 판정 LLM이 쓰는 글이라 길이를 통제할 수 없어 TEXT로 둔다. 화면에 맞는 길이는 판정 프롬프트에서 맞춘다.
-- 유니크 제약의 인덱스가 job_requirement_id로 시작해서, 역량별 조회와 삭제에 따로 인덱스를 두지 않는다.
CREATE TABLE requirement_recommendations
(
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_requirement_id    BIGINT                   NOT NULL REFERENCES job_requirements (id) ON DELETE CASCADE,
    resource_source       VARCHAR(40)              NOT NULL,
    resource_external_key VARCHAR(512)             NOT NULL,
    verdict               VARCHAR(20)              NOT NULL CHECK (verdict IN ('MATCH', 'PARTIAL', 'NOT_MATCH')),
    reason                TEXT                     NOT NULL,
    description           TEXT,
    evidence              JSONB                    NOT NULL,
    similarity_score      DOUBLE PRECISION         NOT NULL,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_requirement_recommendations_resource UNIQUE (job_requirement_id, resource_source, resource_external_key)
);
