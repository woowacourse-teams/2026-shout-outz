-- 프로젝트 기술 이야기 자료 제보.
-- 팀원이 자기 프로젝트 기술 이야기에서 필요 없는 PR, 팀 문서를 고르거나(REMOVE) 빠진 자료의 GitHub 주소를 알려 준다(ADD).
-- 필요 없는 자료는 requirement_recommendations 처럼 (source, external_key) 로 가리키고 외래 키는 걸지 않는다.
-- 자료를 다시 적재하면 resource_documents.id 가 바뀔 수 있어서다.
-- 운영자가 제보를 보고 처리하면 status 와 처리한 관리자(handled_by), 처리 시각(handled_at)을 남긴다.
CREATE TABLE resource_reports
(
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id            BIGINT                   NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    user_id               BIGINT                   NOT NULL REFERENCES users (id),
    kind                  VARCHAR(20)              NOT NULL CHECK (kind IN ('REMOVE', 'ADD')),
    resource_source       VARCHAR(40),
    resource_external_key VARCHAR(512),
    url                   VARCHAR(500),
    memo                  VARCHAR(500),
    status                VARCHAR(20)              NOT NULL CHECK (status IN ('OPEN', 'ACCEPTED', 'REJECTED')),
    handled_by            BIGINT REFERENCES users (id),
    handled_at            TIMESTAMP WITH TIME ZONE,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT resource_reports_target_check CHECK (
        (kind = 'REMOVE' AND resource_source IS NOT NULL AND resource_external_key IS NOT NULL AND url IS NULL)
        OR (kind = 'ADD' AND resource_source IS NULL AND resource_external_key IS NULL AND url IS NOT NULL)
    )
);

-- 같은 사람이 같은 자료를 두 번 '필요 없어요'로 제보하지 않게 막는다.
CREATE UNIQUE INDEX uq_resource_reports_removal
    ON resource_reports (user_id, resource_source, resource_external_key)
    WHERE kind = 'REMOVE';

-- 같은 사람이 같은 주소를 두 번 '추가해 주세요'로 제보하지 않게 막는다.
CREATE UNIQUE INDEX uq_resource_reports_addition
    ON resource_reports (user_id, url)
    WHERE kind = 'ADD';

-- 프로젝트 기술 이야기에서 내가 보낸 제보를 찾는다.
CREATE INDEX idx_resource_reports_project_user
    ON resource_reports (project_id, user_id);

-- 관리자 목록은 상태별 최신순으로 읽는다.
CREATE INDEX idx_resource_reports_status_created
    ON resource_reports (status, created_at DESC, id DESC);
